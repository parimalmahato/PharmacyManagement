namespace Pharmacy.Application.Assistant;

/// <summary>
/// A trusted user-guide section with a stable identifier used to connect answers to their retrieved context.
/// </summary>
public sealed record HelpSource(string Id, string Title, string Content);
/// <summary>
/// Help text, generation mode and supporting guide sections; retrieval and generation modes describe which services actually succeeded.
/// </summary>
public sealed record HelpAnswer(string Answer, string Mode, IReadOnlyList<HelpSource> Sources)
{
    /// <summary>
    /// Actual source-retrieval strategy, kept separate from whether an answer was generated by an AI provider.
    /// </summary>
    public string Retrieval { get; init; } = "keyword";
}

/// <summary>
/// Retrieves approved help content independently of the generation provider; default asynchronous retrieval preserves synchronous implementations.
/// </summary>
public interface IHelpKnowledge
{
    /// <summary>
    /// Returns approved guide sections relevant to a question using the implementation&apos;s synchronous retrieval strategy.
    /// </summary>
    IReadOnlyList<HelpSource> Search(string question);
    /// <summary>
    /// Identifies the retrieval strategy reported to the client; synchronous implementations default to keyword retrieval.
    /// </summary>
    string RetrievalMode => "keyword";
    /// <summary>
    /// Retrieves approved sections asynchronously; the default implementation delegates to synchronous search for providers without asynchronous I/O.
    /// </summary>
    Task<IReadOnlyList<HelpSource>> SearchAsync(string question, CancellationToken ct) => Task.FromResult(Search(question));
}

/// <summary>
/// Generates advisory help from supplied sources or returns null when generation is unavailable; it does not query or change business records.
/// </summary>
public interface IHelpGenerator
{
    /// <summary>
    /// Identifies the generation provider reported alongside a successful generated answer.
    /// </summary>
    string Mode => "langflow";
    /// <summary>
    /// Returns advisory text grounded in the supplied sections, or null when generation cannot be completed; no operational actions are permitted by this contract.
    /// </summary>
    Task<string?> GenerateAsync(string question, IReadOnlyList<HelpSource> sources, CancellationToken ct);
}

/// <summary>
/// Coordinates source retrieval and optional generation while preserving cited guide sections and explicitly identifying fallback behavior.
/// </summary>
public sealed class HelpAssistant(IHelpKnowledge knowledge, IHelpGenerator generator)
{
    /// <summary>
    /// Validates question length, retrieves guide sections and optionally generates a cited answer; no-match and generation-unavailable responses are explicit.
    /// </summary>
    public async Task<HelpAnswer> AskAsync(string question, CancellationToken ct)
    {
        if (string.IsNullOrWhiteSpace(question) || question.Trim().Length > 1000)
            throw new ArgumentException("Enter an application question between 1 and 1,000 characters.");
        var sources = await knowledge.SearchAsync(question.Trim(), ct);
        if (sources.Count == 0)
            return new("I could not find guidance for that question. Try asking about an application task such as billing, returns or passwords. This assistant cannot look up live records or give medical advice.", "no-match", sources) { Retrieval = knowledge.RetrievalMode };

        var generated = await generator.GenerateAsync(question.Trim(), sources, ct);
        return string.IsNullOrWhiteSpace(generated)
            ? new("Here are the matching user-guide sections. Follow the steps in the sources below. Generated AI answers are currently unavailable.", "guide", sources) { Retrieval = knowledge.RetrievalMode }
            : new(generated, generator.Mode, sources) { Retrieval = knowledge.RetrievalMode };
    }
}
